export const deskFonts: DeskFont[] = families.map((entry) => {
  const [family, label] = Array.isArray(entry) ? entry : [entry, entry];
  return { family, label };
});

export function fontFamilyCss(name: string) {
  const family = name.trim();
  if (!family) return undefined;
  return `"${family.replace(/"/g, "")}"`;
}
